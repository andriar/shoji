# transient = shown as a toast, not kept in the panel; scripts run on matching notifications
# 鈴 rin: a small bell for critical notifications (shoji renders it; prefs "rin": false = silent)
RIN = Path.home() / ".local/share/shoji/rin.wav"
try:
    PREFS = json.loads((Path.home() / ".config/shoji/prefs.json").read_text())
except (OSError, ValueError):
    PREFS = {}
rin_on = PREFS.get("rin", True)
if rin_on and RIN.exists():
    cfg["scripts"] = {"rin": {"exec": f"pw-play --volume 0.6 {RIN}", "urgency": "Critical"}}
LOCAL = Path.home() / ".config/shoji/swaync-local.json"
if LOCAL.exists():
    local = json.loads(LOCAL.read_text())
    cfg["notification-visibility"].update(local.get("notification-visibility", {}))
    cfg.setdefault("scripts", {}).update(local.get("scripts", {}))
# 通 batches: note every notification for hypr-widgets' digest card. swaync runs only the first
# script that matches, so this one goes last (after rin and your own)
if PREFS.get("batch"):
    cfg.setdefault("scripts", {})["batch"] = {"exec": "~/.local/bin/shoji-batch note", "app-name": ".*"}
(D / "config.json").write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n")

