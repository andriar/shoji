def reduced_motion():
    try:
        return bool(json.loads((Path.home() / ".config/shoji/prefs.json").read_text()).get("reduced_motion"))
    except (OSError, ValueError):
        return False


def screen_width():
    """Logical width of the focused monitor: the panel starts at its centre line."""
    import subprocess
    try:
        mons = json.loads(subprocess.run(["hyprctl", "monitors", "-j"], capture_output=True, text=True).stdout)
        m = next((m for m in mons if m.get("focused")), mons[0])
        return round(m["width"] / m.get("scale", 1))
    except Exception:
        return 2560


